"""Compare every NCT exit row with its reciprocal entry row and write the errata list.

Mismatches are this tool's output, not a failure, so it exits 0 when it finds them.
"""

from __future__ import annotations

import argparse
import re
from collections import defaultdict
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from zoa_ref.nct_routes import (
    FIELDS,
    VALID_FLOW_SETS,
    Mismatch,
    RowConflicts,
    conflicts_by_row,
    item_key,
    load_data,
    qualifier_key,
)

Row = dict[str, Any]
FlowSets = set[frozenset[str]]
Findings = dict[str, list[dict[str, Any]]]
FoundMismatches = dict[tuple[str, str, str], tuple[Mismatch, FlowSets]]
FoundTwoReceivers = dict[tuple[str, str], tuple[dict[str, Any], FlowSets]]

REPO_ROOT = Path(__file__).resolve().parents[1]
KNOWN_PATH = Path(__file__).with_name("nct_errata_known.md")
DEFAULT_OUT = "docs/nct-errata.md"
BLANK_CELL = "(blank)"
NO_RECIPROCAL_NOTE = (
    "Only one side prints a row with these limits. Tables list only what overrides en "
    "route at any altitude, so a line can be deliberate; a reader checks it against the "
    "other sector's table."
)
TWO_RECEIVERS_NOTE = (
    "One sector's exit table names one receiver and the other sector's entry table "
    "claims the same item and class, and neither side prints the other. A reader "
    "checks which receiver is right."
)
BAY_PARENTS = {"SFOW", "SFOE"}
BAY_FLOWS = BAY_PARENTS | {"OAKE", "SJCE", "SFO10", "SFO19"}
OTHER_FLOW_PAIRS = (("SMFS", "SMFN"), ("RNOS", "RNON"))


def find_findings(data: dict[str, Any]) -> Findings:
    """Compare the SOP rows' reciprocal pairs under every valid flow set.

    Args:
        data: The route data, of which only ``rows`` is read.

    Returns:
        ``mismatches``, one per pair and field; ``two_receivers``, one per exit and entry
        row of one sector that each claim the same item and class from another receiver;
        and ``no_reciprocal``, one per row and flow column for the items and classes no
        reciprocal covers.
    """
    mismatches: FoundMismatches = {}
    missing: dict[tuple[str, str, str], FlowSets] = defaultdict(set)
    two_receivers: FoundTwoReceivers = {}
    for chosen in VALID_FLOW_SETS:
        _record(data["rows"], chosen, mismatches, missing, two_receivers)
    by_id = {row["id"]: row for row in data["rows"]}
    return {
        "mismatches": _mismatch_findings(mismatches),
        "two_receivers": _two_receivers_findings(two_receivers),
        "no_reciprocal": _missing_findings(missing, by_id),
    }


def render(findings: Findings, known_text: str, source: dict[str, Any]) -> str:
    """Render the errata file.

    Args:
        findings: What ``find_findings`` returned.
        known_text: The hand-found errata, placed verbatim.
        source: The data's source versions, with ``sop`` and ``loa`` entries.

    Returns:
        The whole file's text, with LF line endings.
    """
    sop, loa = source["sop"], source["loa"]
    lines = [
        "# NCT SOP and LOA errata",
        "",
        (
            "Generated by `tools/check_nct_reciprocals.py`; don't edit this file by hand. "
            f"Source: SOP {sop['version']} ({sop['date']}), "
            f"LOA {loa['version']} ({loa['date']})."
        ),
        "",
        "## Mismatched cells",
        "",
        "| From | To | Item | Class | Qualifiers | Flows | Field | Exit cell and page | Entry cell and page |",
        "|---|---|---|---|---|---|---|---|---|",
        *_mismatch_lines(findings),
        "",
        "## Two receivers claimed",
        "",
        TWO_RECEIVERS_NOTE,
        "",
        "| From | Exit names | Entry claims | Items | Class | Flows | Exit altitude and page | Entry altitude and page |",
        "|---|---|---|---|---|---|---|---|",
        *_two_receivers_lines(findings),
        "",
        "## No reciprocal row",
        "",
        NO_RECIPROCAL_NOTE,
        "",
        "| From | To | Direction | Items | Class | Qualifiers | Flows | Page |",
        "|---|---|---|---|---|---|---|---|",
        *_missing_lines(findings),
        "",
        "## Found by hand",
        "",
    ]
    return "\n".join(lines) + "\n" + known_text


def main(argv: Sequence[str] | None = None) -> int:
    """Write the errata file and print one summary line.

    Args:
        argv: The command-line arguments, or None to read them from the process.

    Returns:
        0, since a mismatch is the tool's output and not a failure.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out", default=DEFAULT_OUT, help="output file, resolved from the repo root"
    )
    args = parser.parse_args(argv)
    data = load_data()
    findings = find_findings(data)
    known_text = KNOWN_PATH.read_text(encoding="utf-8")
    out = REPO_ROOT / args.out
    with out.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(render(findings, known_text, data["source"]))
    print(
        f"{len(_mismatch_lines(findings))} mismatched cells, "
        f"{len(_missing_lines(findings))} no-reciprocal lines, "
        f"{len(_two_receivers_lines(findings))} two-receiver lines, wrote {out}"
    )
    return 0


def _record(
    all_rows: list[Row],
    chosen: frozenset[str],
    mismatches: FoundMismatches,
    missing: dict[tuple[str, str, str], FlowSets],
    two_receivers: FoundTwoReceivers,
) -> None:
    """Add what the core judged under one flow set to the running aggregates."""
    found = conflicts_by_row(all_rows, chosen)
    for row_id, judged in found.items():
        for item, aircraft in judged.uncovered:
            missing[row_id, item, aircraft].add(chosen)
        for mismatch in judged.mismatches:
            key = (mismatch.exit_row["id"], mismatch.entry_row["id"], mismatch.field)
            mismatches.setdefault(key, (mismatch, set()))[1].add(chosen)
    _collect_two_receivers(found, all_rows, chosen, two_receivers)


def _collect_two_receivers(
    found: dict[str, RowConflicts],
    all_rows: list[Row],
    chosen: frozenset[str],
    two_receivers: FoundTwoReceivers,
) -> None:
    """Group one flow set's uncovered items, pairing their exit and entry rows into the running dict."""
    by_id = {row["id"]: row for row in all_rows}
    groups: dict[
        tuple[str, str, str, frozenset[str]], dict[str, dict[str, list[str]]]
    ] = defaultdict(lambda: {"exit": defaultdict(list), "entry": defaultdict(list)})
    for row_id, judged in found.items():
        row = by_id[row_id]
        quals = frozenset(qualifier_key(name) for name in row["qualifiers"])
        for item, aircraft in judged.uncovered:
            key = (row["from"], item_key(item), aircraft, quals)
            _append_unique(groups[key][row["direction"]][row_id], item)
    for (_, _, aircraft, _), sides in groups.items():
        for exit_id, items in sides["exit"].items():
            for entry_id in sides["entry"]:
                tally, flow_sets = two_receivers.setdefault(
                    (exit_id, entry_id),
                    (_two_receivers_tally(by_id[exit_id], by_id[entry_id]), set()),
                )
                flow_sets.add(chosen)
                for item in items:
                    _append_unique(tally["items"], item)
                _append_unique(tally["classes"], aircraft)


def _mismatch_findings(found: FoundMismatches) -> list[dict[str, Any]]:
    """Build the sorted mismatch findings, altitude first."""
    findings = []
    for (exit_id, entry_id, field), (mismatch, flow_sets) in found.items():
        exit_row, entry_row = mismatch.exit_row, mismatch.entry_row
        findings.append(
            {
                "exit_id": exit_id,
                "entry_id": entry_id,
                "field": field,
                "from": exit_row["from"],
                "to": exit_row["to"],
                "items": mismatch.items,
                "classes": mismatch.classes,
                "qualifiers": _pair_qualifiers(mismatch),
                "flows": _flow_label(flow_sets),
                "exit_value": exit_row[field],
                "entry_value": entry_row[field],
                "exit_page": exit_row["page"],
                "entry_page": entry_row["page"],
            }
        )
    return sorted(
        findings,
        key=lambda finding: (
            FIELDS.index(finding["field"]),
            finding["exit_page"],
            _id_order(finding["exit_id"]),
            _id_order(finding["entry_id"]),
        ),
    )


def _missing_findings(
    found: dict[tuple[str, str, str], FlowSets], by_id: dict[str, Row]
) -> list[dict[str, Any]]:
    """Build the sorted no-reciprocal findings, one per row, flow column and class list."""
    classes_by_item: dict[tuple[str, str], dict[str, list[str]]] = defaultdict(
        lambda: defaultdict(list)
    )
    for (row_id, item, aircraft), flow_sets in found.items():
        classes_by_item[row_id, _flow_label(flow_sets)][item].append(aircraft)
    findings = []
    for (row_id, flows), by_item in classes_by_item.items():
        row = by_id[row_id]
        items_by_classes: dict[tuple[str, ...], list[str]] = defaultdict(list)
        for item, classes in by_item.items():
            items_by_classes[tuple(classes)].append(item)
        for classes, items in items_by_classes.items():
            findings.append(_missing_finding(row, items, classes, flows))
    return sorted(
        findings,
        key=lambda finding: (
            finding["page"],
            _id_order(finding["id"]),
            finding["flows"],
            finding["classes"],
        ),
    )


def _missing_finding(
    row: Row, items: list[str], classes: tuple[str, ...], flows: str
) -> dict[str, Any]:
    """Build one no-reciprocal finding."""
    return {
        "id": row["id"],
        "from": row["from"],
        "to": row["to"],
        "direction": row["direction"],
        "items": items,
        "classes": [aircraft for aircraft in classes if aircraft],
        "qualifiers": ", ".join(row["qualifiers"]),
        "flows": flows,
        "page": row["page"],
    }


def _two_receivers_tally(exit_row: Row, entry_row: Row) -> dict[str, Any]:
    """Build one pair's fixed cells, with its items and classes still to collect."""
    return {
        "exit_id": exit_row["id"],
        "entry_id": entry_row["id"],
        "from": exit_row["from"],
        "exit_to": exit_row["to"],
        "entry_to": entry_row["to"],
        "items": [],
        "classes": [],
        "exit_value": exit_row["altitude"],
        "entry_value": entry_row["altitude"],
        "exit_page": exit_row["page"],
        "entry_page": entry_row["page"],
    }


def _two_receivers_findings(found: FoundTwoReceivers) -> list[dict[str, Any]]:
    """Build the two-receiver findings, by exit page and row id."""
    findings = [
        dict(tally, flows=_flow_label(flow_sets)) for tally, flow_sets in found.values()
    ]
    return sorted(
        findings,
        key=lambda finding: (
            finding["exit_page"],
            _id_order(finding["exit_id"]),
            _id_order(finding["entry_id"]),
        ),
    )


def _flow_label(flow_sets: FlowSets) -> str:
    """Name the Bay choices found, adding an SMF or RNO flow found under one value only."""
    by_bay: dict[frozenset[str], FlowSets] = defaultdict(set)
    for chosen in flow_sets:
        by_bay[chosen & BAY_FLOWS].add(chosen)
    labels = []
    for chosen in VALID_FLOW_SETS:
        bay = chosen & BAY_FLOWS
        if bay in by_bay:
            labels.append(_bay_label(bay, by_bay.pop(bay)))
    return ", ".join(labels)


def _bay_label(bay: frozenset[str], flow_sets: FlowSets) -> str:
    """Name one Bay choice and the SMF or RNO flows it was found under only one way."""
    seen = frozenset().union(*flow_sets)
    names = sorted(bay, key=lambda flow: (flow not in BAY_PARENTS, flow))
    for first, second in OTHER_FLOW_PAIRS:
        values = seen & {first, second}
        if len(values) == 1:
            names.extend(values)
    return "+".join(names)


def _id_order(row_id: str) -> list[Any]:
    """Return a sort key that orders the numbers inside a row id numerically."""
    return [
        int(part) if part.isdigit() else part for part in re.split(r"(\d+)", row_id)
    ]


def _mismatch_lines(findings: Findings) -> list[str]:
    """Render the mismatch table's rows, collapsing identical lines."""
    return list(dict.fromkeys(_mismatch_line(item) for item in findings["mismatches"]))


def _missing_lines(findings: Findings) -> list[str]:
    """Render the no-reciprocal table's rows, collapsing identical lines."""
    return list(
        dict.fromkeys(_missing_line(item) for item in findings["no_reciprocal"])
    )


def _two_receivers_lines(findings: Findings) -> list[str]:
    """Render the two-receiver table's rows, collapsing identical lines."""
    return list(
        dict.fromkeys(_two_receivers_line(item) for item in findings["two_receivers"])
    )


def _mismatch_line(finding: dict[str, Any]) -> str:
    """Render one mismatch as a table row."""
    return _table_line(
        finding["from"],
        finding["to"],
        ", ".join(finding["items"]),
        _classes_cell(finding["classes"]),
        finding["qualifiers"],
        finding["flows"],
        finding["field"],
        _cell_and_page(finding["exit_value"], finding["exit_page"]),
        _cell_and_page(finding["entry_value"], finding["entry_page"]),
    )


def _missing_line(finding: dict[str, Any]) -> str:
    """Render one no-reciprocal finding as a table row."""
    return _table_line(
        finding["from"],
        finding["to"],
        finding["direction"],
        ", ".join(finding["items"]),
        _classes_cell(finding["classes"]),
        finding["qualifiers"],
        finding["flows"],
        f"p{finding['page']}",
    )


def _two_receivers_line(finding: dict[str, Any]) -> str:
    """Render one two-receiver finding as a table row."""
    return _table_line(
        finding["from"],
        finding["exit_to"],
        finding["entry_to"],
        ", ".join(finding["items"]),
        _classes_cell(finding["classes"]),
        finding["flows"],
        _cell_and_page(finding["exit_value"], finding["exit_page"]),
        _cell_and_page(finding["entry_value"], finding["entry_page"]),
    )


def _pair_qualifiers(mismatch: Mismatch) -> str:
    """Render a pair's qualifiers once when they match, otherwise as exit / entry."""
    exit_text = ", ".join(mismatch.exit_row["qualifiers"])
    if mismatch.same_qualifiers:
        return exit_text
    entry_text = ", ".join(mismatch.entry_row["qualifiers"])
    return f"{exit_text or BLANK_CELL} / {entry_text or BLANK_CELL}"


def _classes_cell(classes: list[str]) -> str:
    """Render a class list, naming a blank one."""
    return ", ".join(classes) or BLANK_CELL


def _cell_and_page(value: str, page: int) -> str:
    """Render a printed cell with its page, naming a blank one."""
    return f"{value or BLANK_CELL} (p{page})"


def _append_unique(values: list[str], text: str) -> None:
    """Append a text once, keeping its first-seen order."""
    if text not in values:
        values.append(text)


def _table_line(*cells: str) -> str:
    """Render a Markdown table row, escaping the cell separator."""
    return "| " + " | ".join(cell.replace("|", "\\|") for cell in cells) + " |"


if __name__ == "__main__":
    raise SystemExit(main())
